#!/usr/bin/env python3
# Generate Interlock: a keygen crackme whose license check is a LINEAR SYSTEM over Z/256.
# The validator computes, for each row i:  sum_j A[i][j]*key[j]  (mod 256) == B[i].
# A is chosen invertible mod 2 (=> invertible mod 256), so there is exactly one 16-byte key; the
# player must recognise the check is linear and solve A*key = B (mod 256), then MD5(key)->AES the
# flag. No brute force (2^128), no plaintext flag.
import os, hashlib, random
from Crypto.Cipher import AES
from Crypto.Util.Padding import pad

FLAG = os.environ.get("FLAG", "H7CTF{l1n34r_syst3m_k3yg3n_m0d_256}")
KEY  = b"UNLOCK-SEQ-7Y2AB"           # 16 ascii bytes; what the player recovers
assert len(KEY) == 16
random.seed(0x127E410C)
N = 16

def inv_mod2(mat):
    # is mat invertible over GF(2)? (=> odd determinant => invertible mod 256)
    m = [[mat[i][j] & 1 for j in range(N)] for i in range(N)]
    r = 0
    for c in range(N):
        piv = next((i for i in range(r, N) if m[i][c]), None)
        if piv is None:
            return False
        m[r], m[piv] = m[piv], m[r]
        for i in range(N):
            if i != r and m[i][c]:
                m[i] = [(m[i][k] ^ m[r][k]) for k in range(N)]
        r += 1
    return True

while True:
    A = [[random.randrange(256) for _ in range(N)] for _ in range(N)]
    if inv_mod2(A):
        break

B = [sum(A[i][j] * KEY[j] for j in range(N)) & 0xff for i in range(N)]

key = hashlib.md5(KEY).digest()
blob = AES.new(key, AES.MODE_CBC, b"\x00" * 16).encrypt(pad(FLAG.encode(), 16))

def carr2d(name, m):
    rows = ",\n  ".join("{" + ",".join(str(v) for v in row) + "}" for row in m)
    return f"const unsigned char {name}[{N}][{N}] = {{\n  {rows}\n}};\n"

def carr(name, xs):
    return f"const unsigned char {name}[{len(xs)}] = {{{','.join(str(v) for v in xs)}}};\n"

with open(os.path.join(os.path.dirname(__file__), "interlock_data.h"), "w") as f:
    f.write("/* generated by gen.py */\n")
    f.write(carr2d("A", A))
    f.write(carr("B", B))
    f.write(carr("FLAGBLOB", blob))
    f.write(f"#define N {N}\n#define FLAGBLOB_LEN {len(blob)}\n")

print(f"key={KEY.decode()} A=16x16 B=16 flagblob={len(blob)}B")
