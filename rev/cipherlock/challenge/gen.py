#!/usr/bin/env python3
# Generate Cipherlock: a crackme whose 16-byte key must satisfy a TANGLE of mixed byte constraints -
# XOR couplings, byte-wise PRODUCTS (mod 256, non-linear), and rotate+add. Not cleanly invertible by
# hand (the products break linear algebra), but a clean job for an SMT solver (z3). gen.py verifies
# with z3 that the intended key is the UNIQUE solution, then emits the constants + the AES flag blob.
import os, hashlib, random
import z3
from Crypto.Cipher import AES
from Crypto.Util.Padding import pad

FLAG = os.environ.get("FLAG", "H7CTF{z3_smt_s0lv3s_th3_c1ph3rl0ck}")
KEY  = b"S4T-C0NSTR4INT!7"          # 16 ascii bytes
assert len(KEY) == 16
N = 16
random.seed(0x53415433)
k = list(KEY)

def rol8(v, r): return ((v << r) | (v >> (8 - r))) & 0xff

# constraint constants derived from the real key:
X = [k[i] ^ k[(i + 3) % N] for i in range(N)]                       # XOR couplings
Y = [(k[2 * i] * k[2 * i + 1]) & 0xff for i in range(N // 2)]       # byte products (non-linear)
Z = [(rol8(k[i], 3) + k[(i + 5) % N]) & 0xff for i in range(N)]     # rotate + add

# verify uniqueness with z3 (the solver route must land on exactly this key)
def model_constraints(s, b):
    for i in range(N):
        s.add(b[i] ^ b[(i + 3) % N] == X[i])
    for i in range(N // 2):
        s.add(b[2 * i] * b[2 * i + 1] == Y[i])
    for i in range(N):
        s.add(z3.RotateLeft(b[i], 3) + b[(i + 5) % N] == Z[i])
    for i in range(N):
        s.add(b[i] >= 0x20, b[i] < 0x7f)         # printable ascii key (helps the solver + realism)

b = [z3.BitVec(f"b{i}", 8) for i in range(N)]
s = z3.Solver(); model_constraints(s, b)
assert s.check() == z3.sat
m = s.model()
sol = bytes(m[b[i]].as_long() for i in range(N))
assert sol == KEY, f"solver found different key: {sol}"
s.add(z3.Or([b[i] != k[i] for i in range(N)]))    # any OTHER solution?
assert s.check() == z3.unsat, "key is NOT unique - add more constraints"

key = hashlib.md5(KEY).digest()
blob = AES.new(key, AES.MODE_CBC, b"\x00" * 16).encrypt(pad(FLAG.encode(), 16))

def carr(name, xs):
    return f"const unsigned char {name}[{len(xs)}] = {{{','.join(str(v) for v in xs)}}};\n"

with open(os.path.join(os.path.dirname(__file__), "cipherlock_data.h"), "w") as f:
    f.write("/* generated by gen.py */\n")
    f.write(carr("CX", X)); f.write(carr("CY", Y)); f.write(carr("CZ", Z))
    f.write(carr("FLAGBLOB", blob))
    f.write(f"#define N {N}\n#define FLAGBLOB_LEN {len(blob)}\n")

print(f"key={KEY.decode()} unique=yes constraints={N + N//2 + N} flagblob={len(blob)}B")
