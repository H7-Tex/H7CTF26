#!/usr/bin/env python3
# Generate Tollgate's embedded data: a stripped Go binary (see main.go) validates a 16-byte
# admin token as four big-endian uint32 words, each put through  rotl32(w ^ K, C) + A == TARGET.
# On a valid token it derives sha256(token) -> AES-256-CBC (zero IV, PKCS7) and decrypts the
# admin bootstrap secret (the flag). The token is NOT in the binary; only the per-word constants,
# the targets, and the ciphertext are. Recoverable only by reversing the Go check + inverting it.
import os, struct, hashlib, random
from Crypto.Cipher import AES
from Crypto.Util.Padding import pad

FLAG = os.environ.get("FLAG", "H7CTF{g0_str1pp3d_t0llg4t3_w0rd_r3v}")
TOKEN = b"H7-T0LLG4TE-KEY1"          # 16 bytes; what the player must recover
assert len(TOKEN) == 16
random.seed(0x70115)
M = 0xffffffff

def rotl32(v, r): return ((v << r) | (v >> (32 - r))) & M

K   = [random.randrange(M) for _ in range(4)]
C   = [random.randrange(1, 32) for _ in range(4)]
A   = [random.randrange(M) for _ in range(4)]
w   = [struct.unpack(">I", TOKEN[4*i:4*i+4])[0] for i in range(4)]
TGT = [(rotl32(w[i] ^ K[i], C[i]) + A[i]) & M for i in range(4)]

key  = hashlib.sha256(TOKEN).digest()                 # 32 bytes -> AES-256
blob = AES.new(key, AES.MODE_CBC, b"\x00" * 16).encrypt(pad(FLAG.encode(), 16))

def u32arr(name, xs):
    return f"var {name} = [4]uint32{{{', '.join(hex(x) for x in xs)}}}\n"

with open(os.path.join(os.path.dirname(__file__), "data.go"), "w") as f:
    f.write("package main\n\n// generated by gen.py - do not edit\n\n")
    f.write(u32arr("xorK", K))
    f.write(f"var rot = [4]uint{{{', '.join(str(x) for x in C)}}}\n")
    f.write(u32arr("addA", A))
    f.write(u32arr("target", TGT))
    f.write(f"var blob = []byte{{{', '.join(hex(b) for b in blob)}}}\n")

print(f"token={TOKEN.decode()} targets={[hex(t) for t in TGT]} blob={len(blob)}B")
