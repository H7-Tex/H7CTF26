#!/usr/bin/env python3
# Generate the Warden license-validator: a custom stack-VM (see warden.c) whose embedded
# bytecode checks a 16-byte license key with a per-byte invertible transform, and on success
# AES-decrypts the embedded flag blob. The flag is only recoverable by reversing the VM +
# bytecode to derive the license (then MD5(license) -> AES key). Not present in plaintext.
import os, struct, hashlib, random
from Crypto.Cipher import AES
from Crypto.Util.Padding import pad

FLAG = os.environ.get("FLAG", "H7CTF{cust0m_vm_l1c3ns3_w4rd3n_r3v}")
LICENSE = b"H7X-9F2A-COREKEY"        # 16 bytes; what the player must recover
assert len(LICENSE) == 16
random.seed(0xC0FFEE)
X = [random.randrange(256) for _ in range(16)]
Y = [random.randrange(256) for _ in range(16)]
R = [random.randrange(1, 8) for _ in range(16)]

def rol8(v, r): return ((v << r) | (v >> (8 - r))) & 0xff

# target[i] = rol8(((license[i] ^ X[i]) + Y[i]) & 0xff, R[i])
target = [rol8(((LICENSE[i] ^ X[i]) + Y[i]) & 0xff, R[i]) for i in range(16)]

# opcodes: 01 PUSH_INPUT idx | 02 PUSH_IMM b | 03 XOR | 04 ADD | 05 ROL n | 06 CMP_IMM b
# per byte: PUSH_INPUT i; PUSH_IMM X; XOR; PUSH_IMM Y; ADD; ROL R; CMP_IMM target
bc = bytearray()
for i in range(16):
    bc += bytes([0x01, i, 0x02, X[i], 0x03, 0x02, Y[i], 0x04, 0x05, R[i], 0x06, target[i]])
bc += bytes([0x00])                   # HALT

# flag encrypted under MD5(license)
key = hashlib.md5(LICENSE).digest()
blob = AES.new(key, AES.MODE_CBC, b"\x00" * 16).encrypt(pad(FLAG.encode(), 16))

def carr(name, data):
    body = ",".join(str(b) for b in data)
    return f"const unsigned char {name}[{len(data)}] = {{{body}}};\n"

with open(os.path.join(os.path.dirname(__file__), "warden_data.h"), "w") as f:
    f.write("/* generated by gen.py */\n")
    f.write(carr("BYTECODE", bytes(bc)))
    f.write(carr("FLAGBLOB", blob))
    f.write(f"#define BYTECODE_LEN {len(bc)}\n#define FLAGBLOB_LEN {len(blob)}\n")

print(f"license={LICENSE.decode()} bytecode={len(bc)}B flagblob={len(blob)}B")
