#!/usr/bin/env python3
# Generate Ferric's data.rs: a Rust crackme (see ferric.rs). The 16-byte license passes a per-byte
# transform  rotate_left(c ^ XK[i], ROT[i]).wrapping_add(YA[i]) == TARGET[i]; on success it XOR-decrypts
# the flag with a license-derived keystream. Recoverable only by reversing the Rust binary + inverting.
import os, random
FLAG = os.environ.get("FLAG", "H7CTF{3f7b3f564a5524ce863d}")
LICENSE = b"FERRIC-RUST-KEY1"
assert len(LICENSE) == 16
random.seed(0xFE221C)
def rol8(v, r): return ((v << r) | (v >> (8 - r))) & 0xff
XK  = [random.randrange(256) for _ in range(16)]
ROT = [random.randrange(1, 8) for _ in range(16)]
YA  = [random.randrange(256) for _ in range(16)]
TARGET = [(rol8(LICENSE[i] ^ XK[i], ROT[i]) + YA[i]) & 0xff for i in range(16)]
fb = FLAG.encode()
BLOB = [fb[i] ^ LICENSE[i % 16] ^ ((i * 131 + 7) & 0xff) for i in range(len(fb))]
def rarr(name, xs, n=None):
    n = n if n else len(xs)
    return f"pub const {name}: [u8; {n}] = [{', '.join(str(v) for v in xs)}];\n"
with open(os.path.join(os.path.dirname(__file__), "data.rs"), "w") as f:
    f.write("// generated by gen.py\n")
    f.write(rarr("XK", XK)); f.write(rarr("ROT", ROT)); f.write(rarr("YA", YA))
    f.write(rarr("TARGET", TARGET)); f.write(rarr("BLOB", BLOB))
print(f"license={LICENSE.decode()} blob={len(BLOB)}B")
