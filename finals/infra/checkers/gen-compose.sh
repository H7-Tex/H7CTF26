#!/usr/bin/env bash
# gen-compose.sh — build docker-compose.yml for the checker fleet.
# Scans finals/services/*/checker/ for a Dockerfile (ENO protocol v2).
# One MongoDB container is shared across all checkers.
# Also writes checker-refs.env with checker_ref=<url> per service.
#
# Usage:
#   ./gen-compose.sh [--services-dir <path>] [--out <path>] [--mongo-host <ip>]
#     --services-dir  path to finals/services/  (default: <this script>/../../../services)
#     --out           output compose file        (default: stdout)
#     --mongo-host    address checkers use to reach mongo  (default: mongo)
#     --registry      image registry prefix      (default: asia-south1-docker.pkg.dev/h7ctf26/anvil)
#
# Outputs:
#   docker-compose.yml (or stdout)
#   checker-refs.env   (always written next to the compose file, or ./checker-refs.env if --out=-)
#
# Example:
#   ./gen-compose.sh --out /srv/checkers/docker-compose.yml \
#                    --mongo-host 10.60.201.20

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SERVICES_DIR="$(cd "${SCRIPT_DIR}/../../../services" 2>/dev/null || true && pwd 2>/dev/null || echo "${SCRIPT_DIR}/../../../services")"
OUT="-"
MONGO_HOST="mongo"
REGISTRY="asia-south1-docker.pkg.dev/h7ctf26/anvil"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --services-dir) SERVICES_DIR="$2"; shift 2 ;;
    --out)          OUT="$2";          shift 2 ;;
    --mongo-host)   MONGO_HOST="$2";  shift 2 ;;
    --registry)     REGISTRY="$2";    shift 2 ;;
    *) echo "unknown flag: $1" >&2; exit 1 ;;
  esac
done

if [[ ! -d "$SERVICES_DIR" ]]; then
  echo "services dir not found: $SERVICES_DIR" >&2
  exit 1
fi

# --- collect service slugs that have a checker/Dockerfile ---
SERVICES=()
for d in "$SERVICES_DIR"/*/checker/Dockerfile; do
  [[ -f "$d" ]] || continue
  slug="$(basename "$(dirname "$(dirname "$d")")")"
  SERVICES+=("$slug")
done

if [[ ${#SERVICES[@]} -eq 0 ]]; then
  echo "no services with checker/Dockerfile found under $SERVICES_DIR" >&2
  exit 1
fi

echo "found ${#SERVICES[@]} service(s): ${SERVICES[*]}" >&2

# --- write checker-refs.env ---
if [[ "$OUT" == "-" ]]; then
  REFS_FILE="./checker-refs.env"
else
  REFS_FILE="$(dirname "$OUT")/checker-refs.env"
fi

{
  echo "# checker_ref URLs for game_services — import with: psql -c \"UPDATE game_services SET checker_ref = ... WHERE slug = ...\""
  echo "# generated by gen-compose.sh $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  for slug in "${SERVICES[@]}"; do
    safe="${slug//-/_}"
    echo "checker_ref_${safe}=http://checker-${slug}:8000"
  done
} > "$REFS_FILE"
echo "wrote $REFS_FILE" >&2

# --- generate compose YAML ---
generate_compose() {
cat <<'HEADER'
# generated by finals/infra/checkers/gen-compose.sh — do not edit by hand.
# one checker per service + one shared MongoDB.
# all checkers get MONGO_HOST / MONGO_PORT / MONGO_USER / MONGO_PASSWORD via env.

version: "3.9"

x-checker-defaults: &checker-defaults
  restart: unless-stopped
  networks:
    - checkers
  environment: &checker-env
    MONGO_HOST: "${MONGO_HOST:-mongo}"
    MONGO_PORT: "27017"
    MONGO_USER: "checker"
    MONGO_PASSWORD: "${MONGO_PASSWORD:?set MONGO_PASSWORD}"
  depends_on:
    mongo:
      condition: service_healthy
  logging:
    driver: json-file
    options:
      max-size: "20m"
      max-file: "3"

HEADER

echo "services:"

# mongo — one instance shared by all checkers
cat <<'MONGO'
  mongo:
    image: mongo:7.0
    restart: unless-stopped
    networks:
      - checkers
    environment:
      MONGO_INITDB_ROOT_USERNAME: checker
      MONGO_INITDB_ROOT_PASSWORD: "${MONGO_PASSWORD:?set MONGO_PASSWORD}"
    volumes:
      - mongo-data:/data/db
    healthcheck:
      test: ["CMD", "mongosh", "--quiet", "--eval", "db.adminCommand('ping')"]
      interval: 10s
      timeout: 5s
      retries: 5
      start_period: 20s
    deploy:
      resources:
        limits:
          cpus: "1.0"
          memory: 512M

MONGO

for slug in "${SERVICES[@]}"; do
  safe="${slug//-/_}"
  image="${REGISTRY}/checker-${slug}:latest"
  checker_dir="${SERVICES_DIR}/${slug}/checker"

cat <<ENTRY
  checker-${slug}:
    <<: *checker-defaults
    image: ${image}
    build:
      context: ${checker_dir}
      dockerfile: Dockerfile
    deploy:
      resources:
        limits:
          cpus: "0.5"
          memory: 256M
    healthcheck:
      test: ["CMD", "python3", "-c", "import urllib.request; urllib.request.urlopen('http://localhost:8000/')"]
      interval: 15s
      timeout: 5s
      retries: 3
      start_period: 10s
    ports:
      - "127.0.0.1:${PORT:-0}:8000"
    labels:
      h7.service: "${slug}"
      h7.checker_ref: "http://checker-${slug}:8000"

ENTRY
done

echo "volumes:"
echo "  mongo-data:"
echo ""
echo "networks:"
echo "  checkers:"
echo "    driver: bridge"
}

if [[ "$OUT" == "-" ]]; then
  generate_compose
else
  generate_compose > "$OUT"
  echo "wrote $OUT" >&2
fi
